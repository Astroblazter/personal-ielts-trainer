export function getExercisesByTopic(topicId: string): Exercise[] {
  return GRAMMAR_EXERCISES.filter((e) => e.topicId === topicId);
}

export function getExerciseById(id: string): Exercise | undefined {
  return GRAMMAR_EXERCISES.find((e) => e.id === id);
}

export function assertUniqueExerciseIds(): void {
  const ids = GRAMMAR_EXERCISES.map((e) => e.id);
  const dupes = ids.filter((id, i) => ids.indexOf(id) !== i);
  if (dupes.length > 0) {
    throw new Error(`Duplicate exercise IDs: ${dupes.join(', ')}`);
  }
}
